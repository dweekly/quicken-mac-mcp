import { afterEach, beforeEach, describe, expect, it } from "vitest";
import { existsSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";
import { spawnSync } from "node:child_process";
import Database from "better-sqlite3";
import { resolveLiveQuickenDb } from "./fixtures/live-quicken.js";

const ROOT = resolve(__dirname, "..", "..");
const SCRIPT = join(ROOT, "scripts/refresh_schema_doc.py");
const VENV_PYTHON = join(ROOT, ".venv/bin/python");
const PYTHON = existsSync(VENV_PYTHON) ? VENV_PYTHON : "python3";

function metadataPlist(model: string): string {
  return `<?xml version="1.0" encoding="UTF-8"?>
<plist version="1.0"><dict>
  <key>NSStoreModelVersionIdentifiers</key><array><string>${model}</string></array>
  <key>LastOpenedAppInfo</key><dict>
    <key>CFBundleShortVersionString</key><string>9.9</string>
  </dict>
</dict></plist>`;
}

const STALE_DOC = `# Schema

> Captured from Quicken 9.8 for Mac (Core Data model \`ModelBundle 5\`), January 2020.

## Entity Types

There are **1 entity types** in total.

- \`Widget\`

## Table Schemas

\`\`\`sql
CREATE TABLE ZWIDGET (
    Z_PK INTEGER PRIMARY KEY,
    ZOLDNAME VARCHAR
)
\`\`\`

\`\`\`sql
CREATE TABLE Z_PRIMARYKEY (
    Z_NAME VARCHAR,
    Z_ENT INTEGER
)
\`\`\`

\`\`\`sql
CREATE TABLE Z_METADATA (
    Z_VERSION INTEGER,
    Z_PLIST BLOB
)
\`\`\`

## Indexes

All 0 indexes.

<!-- indexes:start (generated by scripts/refresh_schema_doc.py) -->

<!-- indexes:end -->
`;

describe("refresh_schema_doc.py", () => {
  let directory: string;
  let databasePath: string;
  let docPath: string;

  function buildDatabase(model = "ModelBundle 6") {
    const db = new Database(databasePath);
    db.exec(`
      CREATE TABLE Z_PRIMARYKEY (Z_NAME VARCHAR, Z_ENT INTEGER);
      CREATE TABLE Z_METADATA (Z_VERSION INTEGER, Z_PLIST BLOB);
      CREATE TABLE ZWIDGET (Z_PK INTEGER PRIMARY KEY, ZNEWNAME VARCHAR);
      CREATE INDEX ZWIDGET_ZNEWNAME_INDEX ON ZWIDGET (ZNEWNAME);
      INSERT INTO Z_PRIMARYKEY VALUES ('Widget', 1);
    `);
    db.prepare("INSERT INTO Z_METADATA VALUES (1, ?)").run(
      Buffer.from(metadataPlist(model))
    );
    return db;
  }

  function run(...extra: string[]) {
    return spawnSync(PYTHON, [SCRIPT, "--db", databasePath, "--doc", docPath, ...extra], {
      encoding: "utf8",
    });
  }

  beforeEach(() => {
    directory = mkdtempSync(join(tmpdir(), "quicken-schema-doc-"));
    databasePath = join(directory, "data.sqlite");
    docPath = join(directory, "schema.md");
    writeFileSync(docPath, STALE_DOC);
  });

  afterEach(() => {
    rmSync(directory, { recursive: true, force: true });
  });

  it("--check reports drift and leaves the document alone", () => {
    buildDatabase().close();
    const result = run("--check");
    expect(result.status, result.stderr).toBe(1);
    expect(result.stdout).toContain("DRIFT");
    expect(readFileSync(docPath, "utf8")).toBe(STALE_DOC);
  });

  it("rewrites tables, indexes, and the capture line, after which --check passes", () => {
    buildDatabase().close();
    const refreshed = run();
    expect(refreshed.status, refreshed.stdout + refreshed.stderr).toBe(0);

    const doc = readFileSync(docPath, "utf8");
    expect(doc).toContain("ZNEWNAME VARCHAR");
    expect(doc).not.toContain("ZOLDNAME");
    expect(doc).toContain("- `ZWIDGET_ZNEWNAME_INDEX` on `ZNEWNAME`");
    expect(doc).toContain("All 1 indexes");
    expect(doc).toContain("Quicken 9.9 for Mac (Core Data model `ModelBundle 6`)");

    const checked = run("--check");
    expect(checked.status, checked.stdout).toBe(0);
    expect(checked.stdout).toContain("OK");
  });

  it("flags tables and entities that need a hand-written section", () => {
    const db = buildDatabase();
    db.exec("CREATE TABLE ZGADGET (Z_PK INTEGER PRIMARY KEY)");
    db.exec("INSERT INTO Z_PRIMARYKEY VALUES ('Gadget', 2)");
    db.close();

    const result = run();
    expect(result.status).toBe(1);
    expect(result.stdout).toContain("table has no section yet: ZGADGET");
    expect(result.stdout).toContain("entity is not listed: Gadget");
  });

  it("treats a file from an older Quicken as expected difference, not drift", () => {
    buildDatabase("ModelBundle 4").close();
    const result = run("--check");
    expect(result.status, result.stdout).toBe(0);
    expect(result.stdout).toContain("SKIPPED");
    expect(readFileSync(docPath, "utf8")).toBe(STALE_DOC);
  });

  it("refuses a non-Quicken file without echoing its path", () => {
    new Database(databasePath).exec("CREATE TABLE T (A)");
    const result = run("--check");
    expect(result.status).toBe(2);
    expect(result.stderr).toContain("not an unlocked Quicken database");
    expect(result.stderr).not.toContain(directory);
  });
});

const LIVE_DB = resolveLiveQuickenDb("schema-doc.test.ts", ["ZTRANSACTION"]);

(LIVE_DB ? describe : describe.skip)("docs/schema.md drift against the live file", () => {
  it("matches the open Quicken file's tables, indexes, and entities", () => {
    const result = spawnSync(PYTHON, [SCRIPT, "--db", LIVE_DB!, "--check"], {
      encoding: "utf8",
    });
    expect(result.status, result.stdout + result.stderr).toBe(0);
  });
});
