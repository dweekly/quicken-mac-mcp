#!/usr/bin/env python3
"""Keep docs/schema.md in step with a live Quicken For Mac database.

Why: the schema reference is hand-organized prose around machine-derivable
facts (CREATE TABLE statements, the index list, the entity list). Quicken
changes those facts between releases, and nothing told us when it did.

  refresh_schema_doc.py --db <file.quicken/data>           rewrite the derivable parts
  refresh_schema_doc.py --db <file.quicken/data> --check   report drift, change nothing

The database is opened read-only and only structural names are read or
printed: no rows from any financial table.

Exit codes: 0 in step (or the file is from an older Quicken than the capture,
which is not drift), 1 drift or sections that need a human, 2 could not run.
"""

from __future__ import annotations

import argparse
import datetime
import difflib
import os
import plistlib
import re
import sqlite3
import sys
from pathlib import Path

DEFAULT_DOC = Path(__file__).resolve().parent.parent / "docs" / "schema.md"
HEADER = re.compile(
    r"^> Captured from Quicken (?P<app>\S+) for Mac"
    r"(?: \(Core Data model `(?P<model>[^`]+)`\))?, (?P<when>[^.\n]+)\.$",
    re.M,
)
TABLE_BLOCK = re.compile(r'```sql\nCREATE TABLE "?(\w+)"? \(\n.*?\n\)\n```', re.S)
INDEX_START = "<!-- indexes:start (generated by scripts/refresh_schema_doc.py) -->"
INDEX_END = "<!-- indexes:end -->"
JOIN_TABLE = re.compile(r"^Z_\d+[A-Z]")


class CannotRun(Exception):
    pass


def split_columns(body: str) -> list[str]:
    parts, depth, current = [], 0, ""
    for char in body:
        if char == "(":
            depth += 1
        elif char == ")":
            depth -= 1
        if char == "," and depth == 0:
            parts.append(current.strip())
            current = ""
        else:
            current += char
    if current.strip():
        parts.append(current.strip())
    return parts


def format_table(sql: str) -> str:
    head = sql[: sql.index("(")].strip()
    body = sql[sql.index("(") + 1 : sql.rindex(")")]
    columns = ",\n".join("    " + column for column in split_columns(body))
    return f"```sql\n{head} (\n{columns}\n)\n```"


def model_number(identifier: str | None) -> int | None:
    match = re.search(r"(\d+)\s*$", identifier or "")
    return int(match.group(1)) if match else None


def read_live(db_path: str) -> dict:
    if not os.path.isfile(db_path):
        raise CannotRun("the database file does not exist")
    try:
        connection = sqlite3.connect(f"file:{db_path}?mode=ro", uri=True)
        tables = {
            name: sql
            for name, sql in connection.execute(
                "SELECT name, sql FROM sqlite_master "
                "WHERE type = 'table' AND name NOT LIKE 'sqlite_%'"
            )
        }
        if "Z_PRIMARYKEY" not in tables or "Z_METADATA" not in tables:
            raise CannotRun(
                "this is not an unlocked Quicken database (is Quicken open?)"
            )
        indexes = connection.execute(
            "SELECT name, tbl_name, sql FROM sqlite_master "
            "WHERE type = 'index' AND sql IS NOT NULL"
        ).fetchall()
        entities = [
            row[0] for row in connection.execute("SELECT Z_NAME FROM Z_PRIMARYKEY")
        ]
        (blob,) = connection.execute("SELECT Z_PLIST FROM Z_METADATA").fetchone()
        connection.close()
    except sqlite3.Error as error:
        raise CannotRun(f"SQLite could not read the database ({error})") from None

    metadata = plistlib.loads(blob) if blob else {}
    identifiers = metadata.get("NSStoreModelVersionIdentifiers") or [None]
    app = (metadata.get("LastOpenedAppInfo") or {}).get("CFBundleShortVersionString")
    return {
        "tables": tables,
        "indexes": indexes,
        "entities": entities,
        "model": identifiers[0],
        "app": app,
    }


def render_indexes(live: dict) -> str:
    by_table: dict[str, list[tuple[str, list[str]]]] = {}
    for name, table, sql in live["indexes"]:
        if JOIN_TABLE.match(table):
            continue
        columns = [
            part.strip().split()[0]
            for part in sql[sql.rindex("(") + 1 : sql.rindex(")")].split(",")
        ]
        by_table.setdefault(table, []).append((name, columns))
    lines = [INDEX_START, ""]
    for table in sorted(by_table):
        lines.append(f"**{table}**")
        lines.append("")
        for name, columns in sorted(by_table[table]):
            shown = (
                f"`{columns[0]}`"
                if len(columns) == 1
                else "`(" + ", ".join(columns) + ")`"
            )
            lines.append(f"- `{name}` on {shown}")
        lines.append("")
    lines.append(INDEX_END)
    return "\n".join(lines)


def rebuild(doc: str, live: dict) -> tuple[str, list[str]]:
    """Return the regenerated document and the problems only a human can fix."""
    manual: list[str] = []

    documented: set[str] = set()

    def replace_block(match: re.Match) -> str:
        name = match.group(1)
        documented.add(name)
        if name not in live["tables"]:
            return match.group(0)
        return format_table(live["tables"][name])

    doc = TABLE_BLOCK.sub(replace_block, doc)
    for name in sorted(documented - set(live["tables"])):
        manual.append(f"documented table no longer exists: {name}")
    for name in sorted(set(live["tables"]) - documented):
        manual.append(f"table has no section yet: {name}")

    if INDEX_START in doc and INDEX_END in doc:
        start = doc.index(INDEX_START)
        end = doc.index(INDEX_END) + len(INDEX_END)
        doc = doc[:start] + render_indexes(live) + doc[end:]
    else:
        manual.append("the index list markers are missing from the document")
    doc = re.sub(r"All \d+ indexes", f"All {len(live['indexes'])} indexes", doc)

    try:
        section = doc[doc.index("## Entity Types") : doc.index("## Table Schemas")]
    except ValueError:
        section = ""
        manual.append("the Entity Types section is missing from the document")
    listed = set(re.findall(r"^- `(\w+)`", section, re.M))
    for name in sorted(set(live["entities"]) - listed):
        manual.append(f"entity is not listed: {name}")
    for name in sorted(listed - set(live["entities"])):
        manual.append(f"listed entity no longer exists: {name}")
    doc = re.sub(
        r"\*\*\d+ entity types\*\*", f"**{len(live['entities'])} entity types**", doc
    )
    return doc, manual


def set_header(doc: str, live: dict, when: str) -> str:
    line = (
        f"> Captured from Quicken {live['app']} for Mac "
        f"(Core Data model `{live['model']}`), {when}."
    )
    return HEADER.sub(lambda _match: line, doc, count=1)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--db", default=os.environ.get("QUICKEN_DB_PATH"))
    parser.add_argument("--doc", type=Path, default=DEFAULT_DOC)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()

    try:
        if not args.db:
            raise CannotRun("pass --db or set QUICKEN_DB_PATH")
        if not args.doc.is_file():
            raise CannotRun("the schema document does not exist")
        live = read_live(os.path.expanduser(args.db))
        original = args.doc.read_text(encoding="utf-8")
        header = HEADER.search(original)
        if not header:
            raise CannotRun("the document has no 'Captured from Quicken' line")
    except CannotRun as problem:
        print(f"refresh_schema_doc: cannot run: {problem}", file=sys.stderr)
        return 2

    captured, running = model_number(header.group("model")), model_number(live["model"])
    if captured is not None and running is not None and running < captured:
        print(
            f"SKIPPED: this file uses {live['model']}, older than the documented "
            f"{header.group('model')}. Differences are expected, not drift."
        )
        return 0

    rebuilt, manual = rebuild(original, live)
    same_release = (
        header.group("app") == live["app"] and header.group("model") == live["model"]
    )
    content_changed = rebuilt != original

    if args.check:
        if not content_changed and not manual and same_release:
            print(f"OK: docs/schema.md matches {live['model']} (Quicken {live['app']}).")
            return 0
        print(
            f"DRIFT: docs/schema.md was captured from Quicken {header.group('app')} "
            f"({header.group('model') or 'model not recorded'}); "
            f"this file is Quicken {live['app']} ({live['model']})."
        )
        if content_changed:
            diff = difflib.unified_diff(
                original.splitlines(), rebuilt.splitlines(), lineterm="", n=0
            )
            changes = [
                line
                for line in diff
                if line[:1] in "+-" and line[:3] not in ("+++", "---")
            ]
            for line in changes[:20]:
                print(f"  {line}")
            if len(changes) > 20:
                print(f"  ... and {len(changes) - 20} more changed lines")
        for item in manual:
            print(f"  needs a human: {item}")
        print("  fix: python3 scripts/refresh_schema_doc.py --db <file.quicken/data>")
        return 1

    if content_changed or not same_release:
        when = datetime.date.today().strftime("%B %Y")
        rebuilt = set_header(rebuilt, live, when)
        args.doc.write_text(rebuilt, encoding="utf-8")
        print(f"Rewrote the generated parts for Quicken {live['app']} ({live['model']}).")
    else:
        print("Nothing to rewrite.")
    for item in manual:
        print(f"  needs a human: {item}")
    return 1 if manual else 0


if __name__ == "__main__":
    sys.exit(main())
